/**
 * Check if a hero image path is valid (exists and is known).
 */
export function hasValidHeroImage(heroImage?: string): boolean {
  if (!heroImage) return false;
  if (heroImage.startsWith('https://')) return true;
  return VALID_HERO_IMAGES.has(heroImage);
}
